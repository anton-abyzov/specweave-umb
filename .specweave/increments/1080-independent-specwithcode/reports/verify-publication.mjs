import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {readFileSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const slug='anton-abyzov/specwithcode';
const api=(path)=>JSON.parse(execFileSync('gh',['api',`repos/${slug}${path?'/'+path:''}`],{encoding:'utf8'}));
const commit=api('commits/main');
const head=commit.sha;
const file=(path)=>Buffer.from(api(`contents/${path}?ref=${head}`).content,'base64').toString('utf8');
const tree=api(`git/trees/${commit.commit.tree.sha}`);
assert.ok(!tree.tree.some(x=>/^(LICENSE|LICENCE|COPYING)(\.(md|txt))?$/i.test(x.path)));
const repo=api('');
const baseline=JSON.parse(readFileSync(new URL('./public-baseline.json',import.meta.url),'utf8'));
const baselineHead=readFileSync(new URL('./public-baseline-head.txt',import.meta.url),'utf8').trim();
assert.equal(repo.id,baseline.repositoryId,'repository identity must survive publication');
const history=api(`compare/${baselineHead}...${head}`);
assert.ok(['ahead','identical'].includes(history.status),'public history must retain the original snapshot');
assert.equal(repo.fork,false);assert.ok(!repo.parent);
assert.notEqual(repo.license?.spdx_id,'MIT','GitHub must not advertise a project-wide MIT license');
const contributors=api('contributors?per_page=100');
assert.ok(contributors.length>0);assert.ok(contributors.every(x=>x.login==='anton-abyzov'));
const readme=file('README.md');
assert.doesNotMatch(readme,/MIT licensed|independent MIT fork|free and open source/i);
assert.match(readme,/No new project-wide license is granted/);
assert.match(readme,/THIRD_PARTY_NOTICES\.md/);
const notices=file('THIRD_PARTY_NOTICES.md');
const appRoot=new URL('../../../../repositories/anton-abyzov/specweave-studio/',import.meta.url);
const original=execFileSync('git',['show','10f39eb9ac80c9a4b7f5097575dd2addc3b6f631:LICENSE'],{cwd:fileURLToPath(appRoot),encoding:'utf8'});
assert.equal(notices.slice(notices.indexOf('MIT License\n')),original);
const pkg=JSON.parse(file('apps/server/package.json'));
assert.equal(pkg.license,'UNLICENSED');
const [major,minor,patch]=pkg.version.split('.').map(Number);
assert.ok(major>1||major===1&&(minor>0||patch>=90),'must preserve released source version');
const expected=process.argv[2]??readFileSync(new URL('./final-public-head.txt',import.meta.url),'utf8').trim();
assert.equal(head,expected,'the verified prepared snapshot must be the published head');
const source=JSON.parse(readFileSync(new URL('./final-main-source-verification.json',import.meta.url),'utf8')).head;
assert.ok(commit.commit.message.includes(source.slice(0,12)),'snapshot must identify the reviewed final main source');
const report={repository:slug,repositoryId:repo.id,head,version:pkg.version,fork:repo.fork,detectedProjectLicense:repo.license?.spdx_id??null,baselineHead,historyStatus:history.status,initialStars:baseline.stars,stars:repo.stargazers_count,contributors:contributors.map(x=>x.login),independentReadme:true,blanketLicenseRemoved:true,inheritedNoticeExact:true};
writeFileSync(new URL('./public-verification.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));
