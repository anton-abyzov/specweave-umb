import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
import {mkdirSync,writeFileSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
const cwd=fileURLToPath(new URL('./template-package/',import.meta.url));
mkdirSync(cwd,{recursive:true});
const npm=(args)=>execFileSync('npm',args,{cwd,encoding:'utf8',maxBuffer:8*1024*1024}).trim();
const version=npm(['view','specweave','version','--prefer-online']);
const parts=version.split('.').map(Number);
assert.ok(parts[0]>3||parts[0]===3&&(parts[1]>1||parts[1]===1&&parts[2]>=11),'template guidance must be in a new published patch');
const packed=JSON.parse(npm(['pack',`specweave@${version}`,'--ignore-scripts','--json','--prefer-online']))[0];
const file=(path)=>execFileSync('tar',['-xOf',packed.filename,`package/${path}`],{cwd,encoding:'utf8'});
const pkg=JSON.parse(file('package.json'));
assert.equal(pkg.version,version);
assert.equal(pkg.license,'MIT','SpecWeave CLI existing license must remain intact');
assert.match(file('src/templates/AGENTS.md.template'),/Honor project identity and licensing/);
assert.match(file('src/templates/AGENTS.md.template'),/never infer license grants or history rewrites from branding changes/);
assert.match(file('src/templates/CLAUDE.md.template'),/preserve required third-party notices and accurate provenance/);
const report={package:'specweave',version,integrity:packed.integrity,agentsIdentityGuidance:true,claudeNoticeGuidance:true,cliExistingLicensePreserved:true};
writeFileSync(new URL('./template-package-verification.json',import.meta.url),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));
